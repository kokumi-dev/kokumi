package e2e

import (
	"strings"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"

	"github.com/kokumi-dev/kokumi/test/e2e/framework"
)

// The signing key is the Secret kokumi-signing-key in the namespace
// kokumi-signing, which the controller generates.
const (
	signingKeySecretName = "kokumi-signing-key"
	signingKeyNamespace  = "kokumi-signing"
)

var _ = Describe("Access control", Label("access"), func() {
	Context("the signing key", Ordered, func() {
		BeforeAll(func() {
			secretWriter := framework.TestdataFile("access/secret-writer.yaml", nil)
			DeferCleanup(func() {
				_, _ = framework.Kubectl("delete", "-f", secretWriter, "--ignore-not-found")
			})
		})

		It("is generated by the controller in a namespace of its own", func() {
			Eventually(func() error {
				_, err := framework.Kubectl("get", "secret", signingKeySecretName, "-n", signingKeyNamespace)
				return err
			}).Should(Succeed())
		})

		It("can be read or written by none of the built-in identities", func() {
			for _, sa := range []string{"kokumi-admin", "kokumi-editor", "kokumi-viewer", "kokumi-server"} {
				for _, verb := range []string{"get", "list", "patch", "delete"} {
					out, _ := framework.KubectlAs(sa, "auth", "can-i", verb, "secret/"+signingKeySecretName, "-n", signingKeyNamespace)
					Expect(strings.TrimSpace(out)).To(Equal("no"), "%s may %s the signing key", sa, verb)
				}
			}
		})

		It("leaves the server its auth Secrets in the install namespace", func() {
			out, _ := framework.KubectlAs("kokumi-server", "auth", "can-i", "list", "secrets", "-n", framework.InstallNamespace)
			Expect(strings.TrimSpace(out)).To(Equal("yes"))
		})

		It("is refused by admission even to a ServiceAccount that RBAC allows to write it", func() {
			framework.ApplyTestdata("", "access/secret-writer.yaml", nil)
			Eventually(func(g Gomega) {
				out, err := framework.KubectlAs("e2e-secret-writer",
					"patch", "secret", signingKeySecretName, "-n", signingKeyNamespace,
					"--type=merge", "-p", `{"metadata":{"labels":{"forged":"true"}}}`)
				g.Expect(err).To(HaveOccurred())
				g.Expect(err.Error() + out).To(ContainSubstring("signing key can only be written"))
			}).Should(Succeed())
		})

		It("can be changed by a cluster admin", func() {
			_, err := framework.Kubectl("label", "secret", signingKeySecretName, "-n", signingKeyNamespace,
				"e2e.kokumi.dev/checked-by=cluster-admin", "--overwrite")
			Expect(err).NotTo(HaveOccurred())
		})
	})
})
